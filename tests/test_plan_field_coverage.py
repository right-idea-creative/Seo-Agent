# Fields allowed to exist without a current consumer.
# Each key is a model label; each value is a set of field names with a justification.
# An empty dict means zero untracked fields are tolerated.
ALLOWED_UNTRACKED: dict[str, set[str]] = {}


# ── Test helpers ──────────────────────────────────────────────────────────────

def _assert_coverage(model_cls, consumed: set[str], label: str) -> None:
    all_fields = set(model_cls.model_fields.keys())
    allowed = ALLOWED_UNTRACKED.get(label, set())
    covered = consumed | allowed

    untracked = all_fields - covered
    assert not untracked, (
        f"\n{label} has fields generated by the planner but never read by any agent:\n"
        + "".join(f"  - {f}\n" for f in sorted(untracked))
        + f"Add them to CONSUMED_{label.upper()}_FIELDS if a consumer exists, "
        f"or to ALLOWED_UNTRACKED['{label}'] with a justification comment."
    )

    phantom = consumed - all_fields
    assert not phantom, (
        f"\n{label} CONSUMED set references fields that no longer exist in the model:\n"
        + "".join(f"  - {f}\n" for f in sorted(phantom))
        + "Update the CONSUMED set to match the current model definition."
    )


# ── Tests ─────────────────────────────────────────────────────────────────────

def test_article_plan_field_coverage():
    _assert_coverage(ArticlePlan, CONSUMED_ARTICLE_PLAN_FIELDS, "ArticlePlan")


def test_section_plan_field_coverage():
    _assert_coverage(SectionPlan, CONSUMED_SECTION_PLAN_FIELDS, "SectionPlan")


def test_faq_plan_field_coverage():
    _assert_coverage(FAQPlan, CONSUMED_FAQ_PLAN_FIELDS, "FAQPlan")


def test_planned_image_field_coverage():
    _assert_coverage(PlannedImage, CONSUMED_PLANNED_IMAGE_FIELDS, "PlannedImage")
