"""
Schema field coverage test.

Every field in ArticlePlan, SectionPlan, FAQPlan, and PlannedImage must be consumed
by at least one downstream agent, or explicitly declared in ALLOWED_UNTRACKED.

This test prevents silent "dead output" — fields the planner generates and pays for
but no agent ever reads. Adding a new schema field without updating a consumer set
causes a loud failure here, forcing an explicit decision.
"""
from models.article_plan import ArticlePlan, FAQPlan, PlannedImage, SectionPlan

# ── Consumed field sets ────────────────────────────────────────────────────────
# Verified against:
#   ArticlePlan.to_generator_block()  → ArticleAgent (article body prompt)
